const RULES = MAP.map(([dev, latin]) => [new RegExp(`(?<![${DEV}])(?:${dev})(?![${DEV}])`, "gu"), latin] as const);

export function latinize(normalized: string): string {
  return RULES.reduce((t, [re, latin]) => t.replace(re, latin), normalized);
}
